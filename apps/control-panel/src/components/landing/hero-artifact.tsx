'use client';

import { useEffect, useMemo, useState } from 'react';

/**
 * Sequel running in Claude Code, in a terminal, on a backdrop it made.
 *
 * Drawn the way Claude Code actually renders: the ask echoed on a `>` line,
 * each MCP call as `⏺ sequel - tool(args)` with its result hanging off a
 * `⎿`, the spinner line carrying a gerund, the elapsed clock, the token count
 * and `esc to interrupt`, and a bordered composer at the bottom. Output
 * scrolls up from the bottom of the pane, as a terminal does.
 *
 * Nothing here calls anything. The tool names are the three this server
 * exposes, the models and prices are the catalogue's own — FLUX at 1024² and
 * four steps is $0.000634 by `estimateCost`, Hailuo is the published $0.28
 * for six seconds at 768p, Music 2.6 is $0.15 a track — and the timings are a
 * recording. The only generation on this page already happened.
 *
 * The images are a liberty: a terminal cannot show them inline. They stand in
 * for what lands in the client, and everything around them is accurate.
 */

interface Call {
  tool: string;
  args: string;
  result: string;
}

interface Scenario {
  prompt: string;
  gerund: string;
  tokens: string;
  calls: Call[];
  output:
    | { kind: 'grid'; srcs: string[]; alt: string }
    | { kind: 'clip'; src: string; alt: string }
    | { kind: 'file'; name: string; meta: string };
  done: string;
}

